// Writes site/src/components/landing/land.ts: which points of a Fibonacci sphere sit on land, as
// a base64 bitmask, for the landing globe's dots. Run once when N changes (the coastline doesn't):
//   cd "$(mktemp -d)" && npm i world-atlas@2.0.2 topojson-client@3.1.0 d3-geo@3.1.1
//   NODE_PATH=$PWD/node_modules node /path/to/scripts/landing_land_mask.mjs
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const require = createRequire(process.env.NODE_PATH + "/");
const { geoContains } = require("d3-geo");
const { feature } = require("topojson-client");
const land = feature(require("world-atlas/land-50m.json"), "land");

const N = 40000; // dots on the whole sphere; about 29% land on land
const golden = Math.PI * (3 - Math.sqrt(5));
const bits = new Uint8Array(Math.ceil(N / 8));
let kept = 0;
for (let i = 0; i < N; i++) {
  // Same formula as fibonacci() in land.ts, so index i means the same point on both sides.
  const y = 1 - (2 * (i + 0.5)) / N;
  const lat = (Math.asin(y) * 180) / Math.PI;
  const lng = ((((i * golden) % (2 * Math.PI)) * 180) / Math.PI + 540) % 360 - 180;
  if (geoContains(land, [lng, lat])) { bits[i >> 3] |= 1 << (i & 7); kept++; }
}
const out = fileURLToPath(new URL("../site/src/components/landing/land.ts", import.meta.url));
writeFileSync(out, `// Generated by scripts/landing_land_mask.mjs from Natural Earth 1:50m land (public domain).
// Bit i is set when point i of an N-point Fibonacci sphere is on land (${kept} of ${N}).
export const N = ${N};
export const LAND = "${Buffer.from(bits).toString("base64")}";

/** Point i of the Fibonacci sphere, as latitude and longitude in degrees. */
export function fibonacci(i: number): [number, number] {
  const y = 1 - (2 * (i + 0.5)) / N;
  const golden = Math.PI * (3 - Math.sqrt(5));
  return [(Math.asin(y) * 180) / Math.PI, ((((i * golden) % (2 * Math.PI)) * 180) / Math.PI + 540) % 360 - 180];
}

/** Every land point, as [lat, lng] pairs. */
export function landPoints(): [number, number][] {
  const bytes = Uint8Array.from(atob(LAND), (c) => c.charCodeAt(0));
  const out: [number, number][] = [];
  for (let i = 0; i < N; i++) if (bytes[i >> 3] & (1 << (i & 7))) out.push(fibonacci(i));
  return out;
}
`);
console.log(`${kept} of ${N} points on land -> ${out}`);
